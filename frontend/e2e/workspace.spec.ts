import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test('register, manage a monitor and publish a status page', async ({ page }) => {
  const suffix = randomUUID().slice(0, 8)
  const email = `playwright-${suffix}@example.com`
  const password = randomUUID()
  const slug = 'playwright-' + suffix
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Контролируйте доступность/ })).toBeVisible()
  await page.getByRole('link', { name: 'Начать мониторинг' }).click()
  await page.getByLabel('Имя', { exact: true }).fill('Playwright')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Создать аккаунт' }).click()
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Новый монитор' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Название').fill('Primary website')
  await dialog.getByLabel('Публичный URL').fill('https://example.com')
  await dialog.getByLabel('Интервал').selectOption('60')
  await dialog.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Монитор добавлен')).toBeVisible()
  await page.getByRole('navigation').getByRole('link', { name: 'Мониторы' }).click()
  const row = page.getByRole('row').filter({ hasText: 'Primary website' })
  await expect(row).toBeVisible()
  await expect(row).toContainText('1 мин')
  await row.getByRole('button', { name: 'Пауза' }).click()
  await expect(row.getByText('На паузе')).toBeVisible()
  await row.getByRole('button', { name: 'Возобновить' }).click()
  await expect(row.getByRole('button', { name: 'Пауза' })).toBeVisible()

  await page.getByRole('navigation').getByRole('link', { name: 'Статус-страницы' }).click()
  await page.getByRole('button', { name: 'Новая страница' }).click()
  await dialog.getByLabel('Название').fill('Service status')
  await dialog.getByLabel('Адрес страницы').fill(slug)
  await dialog.getByLabel('Primary website').check()
  await dialog.getByLabel('Опубликовать страницу').check()
  await dialog.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('/status/' + slug, { exact: false })).toBeVisible()
  const guest = await page.context().browser()!.newPage()
  await guest.goto(new URL('/status/' + slug, page.url()).href)
  await expect(guest.getByRole('heading', { name: 'Service status' })).toBeVisible()
  await expect(guest.getByText('Primary website')).toBeVisible()
  await expect(guest.getByText('https://example.com', { exact: false })).toHaveCount(0)
  await guest.close()

  await page.goto('/app/monitors')
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Удалить' }).click()
  await page.getByRole('button', { name: 'Подтвердить' }).click()
  await expect(page.getByText('Пока нет мониторов')).toBeVisible()
  await page.getByRole('button', { name: 'Выйти' }).click()
  await expect(page).toHaveURL(/\/login$/)
})

test('mobile layout holds and offers guest navigation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const dimensions = await page.evaluate(() => ({ page: document.documentElement.scrollWidth, viewport: window.innerWidth }))
  expect(dimensions.page).toBeLessThanOrEqual(dimensions.viewport)
  await expect(page.getByRole('heading', { name: /Контролируйте доступность/ })).toBeVisible()
  await page.getByRole('link', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Вход в PulseMonitor' })).toBeVisible()
})
